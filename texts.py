def tickets_word(count):
    """Русская плюрализация: 1 билет / 2 билета / 5 билетов."""
    if 11 <= count % 100 <= 14 or count % 10 in (0, 5, 6, 7, 8, 9):
        return "билетов"
    return "билет" if count % 10 == 1 else "билета"


